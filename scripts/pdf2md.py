import re, sys
src, dst = sys.argv[1], sys.argv[2]
lines = open(src, encoding="utf-8", errors="ignore").read().replace("\f", "\n").split("\n")
footer = re.compile(r"^\s*SIGNAL · Build Specification v1\.0\s+\d+ / 36\s*$")
h1 = re.compile(r"^(\d{1,2})\. (How to use|Vision|The needs|Principles|System overview|Architecture|Engine|Rhythms|Ask SIGNAL|Data model|API surface|User interface|LLM layer|Non-functional|Build plan|Testing strategy|Configuration|Future)")
h2 = re.compile(r"^(\d{1,2}\.\d{1,2}) (\S.*)$")
out = ["<!-- Verbatim markdown copy of SIGNAL_Build_Specification.pdf v1.0 (36 pages), generated by pdftotext -layout + scripts/pdf2md.py. Tables and code samples are kept as preformatted text blocks to preserve the original layout. -->", ""]
buf = []
def flush():
    global buf
    while buf and not buf[-1].strip(): buf.pop()
    if buf:
        out.append("```text"); out.extend(buf); out.append("```"); out.append("")
    buf = []
def is_pre(l):
    return l.startswith("   ") or re.search(r"\S {3,}\S", l)
i = 0
prev_blank = True
for raw in lines:
    l = raw.rstrip()
    if footer.match(l): continue
    if h1.match(l):
        flush(); out.append("## " + l); out.append(""); continue
    m = h2.match(l)
    if m and not re.search(r"\S {3,}\S", l):
        flush(); out.append("### " + l); out.append(""); continue
    if l.strip() and is_pre(l):
        buf.append(l); continue
    if not l.strip():
        if buf: buf.append(""); 
        else: out.append("")
        continue
    flush(); out.append(l.strip())
flush()
text = "\n".join(out)
text = re.sub(r"\n{3,}", "\n\n", text)
open(dst, "w", encoding="utf-8").write("# SIGNAL — Build Specification v1.0\n\n" + text)
